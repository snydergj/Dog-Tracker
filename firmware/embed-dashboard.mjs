import { readFile, writeFile } from 'node:fs/promises';

const assets = [
  ['Index', 'index.html'],
  ['Style', 'style.css'],
  ['App', 'app.mjs'],
  ['Gps', 'gps.mjs'],
  ['Geofence', 'geofence.mjs'],
];
const declarations = await Promise.all(assets.map(async ([name, file]) => {
  let source = (await readFile(new URL(`../dist/${file}`, import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
  if (name === 'Index') source = source.replace('<html lang="en">', '<html lang="en" data-tracker-web>');
  if (source.includes(')TRACKER_WEB"')) throw new Error(`Invalid dashboard delimiter in ${file}`);
  return `constexpr char k${name}[] PROGMEM = R"TRACKER_WEB(${source})TRACKER_WEB";`;
}));
await writeFile(new URL('./TrackerOTA/DashboardAssets.h', import.meta.url),
  `// Generated by firmware/embed-dashboard.mjs\n#pragma once\n\nnamespace dashboard {\n${declarations.join('\n')}\n}\n`);
